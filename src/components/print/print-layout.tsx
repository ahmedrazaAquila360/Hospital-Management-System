import type { ReactNode } from "react";
import { Download } from "lucide-react";
import { Button } from "@/components/ui/button";
import { PrintButton } from "@/components/print/print-button";
import type { getClinicSettings } from "@/server/settings/queries";

export async function PrintLayout({
  clinic,
  documentLabel,
  downloadHref,
  downloadFileName,
  children,
}: {
  clinic: Awaited<ReturnType<typeof getClinicSettings>>;
  documentLabel: string;
  downloadHref?: string;
  downloadFileName?: string;
  children: ReactNode;
}) {
  return (
    <div className="min-h-svh bg-neutral-100 py-8 print:bg-white print:py-0">
      <div className="mx-auto mb-4 flex max-w-[8.5in] justify-end gap-2 px-4 print:hidden">
        {downloadHref && (
          <Button asChild variant="outline">
            <a href={downloadHref} download={downloadFileName}>
              <Download /> Download PDF
            </a>
          </Button>
        )}
        <PrintButton />
      </div>
      <div className="mx-auto flex min-h-[11in] w-full max-w-[8.5in] flex-col bg-white p-10 text-neutral-900 shadow-lg print:min-h-0 print:p-0 print:shadow-none">
        <div className="mb-8 flex items-start justify-between border-b border-neutral-200 pb-6">
          <div>
            <h1 className="text-xl font-semibold tracking-tight">{clinic.clinicName}</h1>
            <div className="mt-1 space-y-0.5 text-xs text-neutral-500">
              {clinic.address && <p>{clinic.address}</p>}
              <p>
                {[clinic.phone, clinic.email, clinic.website].filter(Boolean).join(" · ")}
              </p>
            </div>
          </div>
          <div className="text-right">
            <p className="text-sm font-semibold text-neutral-700 uppercase tracking-wide">{documentLabel}</p>
          </div>
        </div>

        <div className="flex-1">{children}</div>

        <footer className="mt-10 border-t border-neutral-200 pt-4 text-center text-[10px] text-neutral-400">
          Generated by {clinic.clinicName}
        </footer>
      </div>
    </div>
  );
}
